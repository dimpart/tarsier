import 'dart:convert';
import 'dart:typed_data';
import 'dart:math';

import 'package:flutter/material.dart';

import 'package:dim_flutter/dim_flutter.dart';
import 'package:dim_flutter/lnc.dart' as lnc;

import 'call_engine.dart';
import 'call_page.dart';


/// Calling states:
///
/// 1. inviting      - dial out, waiting for the peer to accept
/// 2. waiting       - got an invitation, waiting for answering
/// 3. connecting    - accepted, trying to establish connection
/// 4. connected     - connection OK, talking
/// 5. reconnecting  - network broken, trying to reconnect
/// 6. ended         - call over, stay 1 second before auto close
enum CallState { idle, inviting, waiting, connecting, connected, reconnecting, ended }


/// Singleton controller of the voice call window.
///
/// Only one instance of the window is allowed at the same time: while
/// the current window is not closed (i.e. while a meeting ID exists),
/// new popup requests are ignored. The window cannot be closed by swipe
/// gestures nor back button; it closes itself 1 second after entering
/// the 'ended' state, which can only be triggered by the cancel /
/// reject / hang-up buttons.
///
/// The states are driven by two notifications:
/// * kMeetingDialClicked - the user dials a peer from the chat box;
/// * kVompCommandArrived - inbound VoMP signaling (dial/accept/start/
///   reject/cancel/bye/busy), transitions guarded by the current state
///   and the meeting ID as specified in vomp/protocol.md section 3.3
///   (the state machine).
class CallController extends ChangeNotifier with Logging implements lnc.Observer {
  factory CallController() => _instance;
  static final CallController _instance = CallController._internal();
  CallController._internal() {
    var nc = lnc.NotificationCenter();
    nc.addObserver(this, NotificationNames.kMeetingDialClicked);
    nc.addObserver(this, NotificationNames.kVompCommandArrived);
  }

  @override
  void dispose() {
    var nc = lnc.NotificationCenter();
    nc.removeObserver(this, NotificationNames.kVompCommandArrived);
    nc.removeObserver(this, NotificationNames.kMeetingDialClicked);
    super.dispose();
  }

  /// Ringing timeout: 45 seconds without accept/reject -> auto cancel
  /// (vomp/protocol.md section 3.3).
  static const Duration _ringingTimeout = Duration(seconds: 45);

  /// Connecting timeout: 10 seconds without any packet from the peer ->
  /// 'line unreachable', end the call (vomp/protocol.md section 3.4).
  static const Duration _connectingTimeout = Duration(seconds: 10);

  CallState _state = CallState.idle;
  CallState get state => _state;

  /// current meeting ID: non-null while the window is showing. It also
  /// gates the inbound signaling - commands of other meetings are ignored.
  ID? _meeting;
  ID? get meeting => _meeting;

  ID? _peer;
  ID? get peer => _peer;

  /// meeting key (32 bytes, generated by the caller on accept) and my
  /// senderId in the media nonces: 1 = initiator, 2 = receiver
  Uint8List? _meetingKey;
  int _localId = 0;

  /// next call suffix: starts at a random number between 10k and 1e9, and
  /// increments by one for every new call
  int _nextCallSuffix = Random().nextInt(999990000) + 10000;

  DateTime? _talkSince;

  /// audio params proposed by the dial (the caller's capability probe
  /// result, signaling.md section 1)
  Map? _proposedMedia;

  /// audio params confirmed by the accept: the dial proposal intersected
  /// with the local capability (signaling.md section 2)
  Map? _confirmedMedia;

  CallEngine? _engine;

  //
  //  Popup control
  //

  /// State 1: dial out to the peer, waiting for it to accept.
  Future<void> call(ID peer) async {
    if (_meeting != null) {
      assert(false, 'call window is showing for: $_peer');
      return;
    }
    GlobalVariable shared = GlobalVariable();
    User? me = await shared.facebook.currentUser;
    if (me == null) {
      logError('failed to get current user');
      return;
    }
    // local audio capability: probe the native Opus coder pair; the
    // result is the media proposed by the dial (signaling.md section 1)
    Map media = await _probeMedia();
    _proposedMedia = media;
    // my own port info: no ready bridge means no fallback path,
    // the direct connections may still work, so keep going anyway
    List<BridgeEntry> myBridges = MagpieClient.instance.myBridges;
    List<SocketEntry> mySockets = MagpieClient.instance.mySockets;
    if (myBridges.isEmpty) {
      logWarning('no ready bridge before dialing: $peer');
    }
    // new meeting ID: a temporary Polylogue ID derived from my
    // meta.seed = 'call-xxxx' (vomp/protocol.md section 3.0)
    ID? meeting = await _newMeetingID(me);
    if (meeting == null) {
      logError('failed to generate meeting ID');
      return;
    }
    _meeting = meeting;
    _peer = peer;
    _localId = 1;
    _changeState(CallState.inviting);
    _startTimeoutTimer(DateTime.now());
    unawaited(_popup());
    // send act='dial' with members, port info and proposed media
    unawaited(shared.emitter.sendContent(VompContent.dial(meeting,
      members: [me.identifier, peer],
      bridges: _packBridges(myBridges),
      sockets: _packSockets(mySockets),
      media: media), receiver: peer));
  }

  /// State 2: got an invitation from the peer, waiting for answering.
  /// The timeout counts from the dial envelope time, not local receive time.
  /// [media] is the audio params proposed by the dial (signaling.md section 1).
  Future<void> invited(ID peer, {ID? meeting, DateTime? dialTime, Map? media}) async {
    if (_meeting != null) {
      assert(false, 'call window is showing for: $_peer');
      return;
    }
    _meeting = meeting;
    _peer = peer;
    _localId = 2;
    _proposedMedia = media;
    _changeState(CallState.waiting);
    _startTimeoutTimer(dialTime ?? DateTime.now());
    unawaited(_popup());
  }

  //
  //  Button events (fired by the call window)
  //

  /// State 2 -> 3: accepted by the local user.
  Future<void> accept() async {
    if (_state != CallState.waiting) {
      assert(false, 'accepting while state = $_state');
      return;
    }
    ID? meeting = _meeting;
    if (meeting == null) {
      logError('failed to get meeting ID');
      return;
    }
    _timer?.cancel();
    _changeState(CallState.connecting);
    _startConnectingTimer();
    // talk seconds count from the accept to the bye (protocol.md section 3.1)
    _talkSince = DateTime.now();
    // reply act='accept' with my port info and the confirmed media: the
    // dial proposal intersected with the local capability (either side
    // without Opus => 'pcm16', signaling.md section 2)
    Map local = await _probeMedia();
    Map media = _negotiateMedia(_proposedMedia ?? local, local);
    _confirmedMedia = media;
    List<BridgeEntry> myBridges = MagpieClient.instance.myBridges;
    List<SocketEntry> mySockets = MagpieClient.instance.mySockets;
    await _sendSignaling(VompContent.accept(meeting,
      bridges: _packBridges(myBridges),
      sockets: _packSockets(mySockets),
      media: media));
  }

  /// State 1/3/5 -> 6: canceled by the local user.
  Future<void> cancel() async {
    if (_state != CallState.inviting && _state != CallState.connecting
        && _state != CallState.reconnecting) {
      assert(false, 'canceling while state = $_state');
      return;
    }
    ID? meeting = _meeting;
    if (meeting == null) {
      logError('failed to get meeting ID');
      return;
    }
    // send act='cancel' to abort the still-ringing call
    VompContent content = VompContent.cancel(meeting);
    await _sendSignaling(content);
    await _saveRecord('Call cancelled.');
    _endCall();
  }

  /// State 2 -> 6: rejected by the local user.
  Future<void> reject() async {
    if (_state != CallState.waiting) {
      assert(false, 'rejecting while state = $_state');
      return;
    }
    ID? meeting = _meeting;
    if (meeting == null) {
      logError('failed to get meeting ID');
      return;
    }
    // send act='reject' to decline the invitation
    VompContent content = VompContent.reject(meeting);
    await _sendSignaling(content);
    await _saveRecord('Call rejected.');
    _endCall();
  }

  /// State 4 -> 6: hung up by the local user.
  Future<void> hangUp() async {
    if (_state != CallState.connected) {
      assert(false, 'hanging up while state = $_state');
      return;
    }
    ID? meeting = _meeting;
    if (meeting == null) {
      logError('failed to get meeting ID');
      return;
    }
    // send act='bye' with the sender-measured talk seconds
    double seconds = _talkSince == null
        ? 0 : DateTime.now().difference(_talkSince!).inMilliseconds / 1000;
    VompContent content = VompContent.bye(meeting, duration: seconds);
    await _sendSignaling(content);
    await _saveRecord('Call ended (${formatMeetingDuration(seconds)}).');
    _endCall();
  }

  //
  //  Engine callbacks
  //

  /// State 1 -> 3: invitation accepted by the peer.
  void answered() {
    if (_state != CallState.inviting) {
      assert(false, 'answered while state = $_state');
      return;
    }
    _timer?.cancel();
    _changeState(CallState.connecting);
    _startConnectingTimer();
  }

  /// State 3/5 -> 4: connection established.
  void connected() {
    if (_state != CallState.connecting && _state != CallState.reconnecting) {
      assert(false, 'connected while state = $_state');
      return;
    }
    _connectingTimer?.cancel();
    _connectingTimer = null;
    // the talk start point was set on accept; a reconnect after a
    // connection loss must not reset it
    _changeState(CallState.connected);
  }

  /// State 4 -> 5: connection lost.
  void connectionLost() {
    if (_state != CallState.connected) {
      assert(false, 'connection lost while state = $_state');
      return;
    }
    _changeState(CallState.reconnecting);
  }

  //
  //  Notification events
  //

  @override
  Future<void> onReceiveNotification(lnc.Notification notification) async {
    String name = notification.name;
    Map? userInfo = notification.userInfo;
    if (name == NotificationNames.kMeetingDialClicked) {
      ID? chat = userInfo?['ID'];
      if (chat == null) {
        assert(false, 'failed to get chat ID: $userInfo');
        return;
      }
      await call(chat);
    } else if (name == NotificationNames.kVompCommandArrived) {
      await _handleVompCommand(userInfo);
    }
  }

  //
  //  Internals
  //

  /// Drive the calling states with the inbound VoMP signaling: every act
  /// checks the current state, the sender and the meeting ID before
  /// transitioning, as specified in vomp/protocol.md section 3.3
  /// (the state machine).
  Future<void> _handleVompCommand(Map? userInfo) async {
    ID? sender = userInfo?['sender'];
    String? act = userInfo?['action'];
    VompContent? vomp = userInfo?['content'];
    if (sender == null || act == null || vomp == null) {
      assert(false, 'vomp command error: $userInfo');
      return;
    }
    // signaling of another meeting (or none showing) is not for me;
    // except the dial, which is only accepted when idle
    if (_meeting != null) {
      if (act == VompContent.ACT_DIAL) {
        // a new call arrives while I am calling/talking: auto-reply
        // 'busy' instead of dropping it (protocol.md section 3.3)
        await _dialArrived(sender, vomp);
        return;
      }
      bool sameMeeting = _meeting!.isSameAs(vomp.meeting);
      bool samePeer = sender.isSameAs(_peer);
      if (!sameMeeting || !samePeer) {
        logWarning('drop foreign command: $act, meeting: ${vomp.meeting}, sender: $sender');
        return;
      }
    } else if (act != VompContent.ACT_DIAL) {
      return; // no call window: only the dial may create one
    }
    switch (act) {
      case VompContent.ACT_DIAL:
        await _dialArrived(sender, vomp);
        break;

      case VompContent.ACT_ACCEPT:
        await _acceptArrived(sender, vomp);
        break;

      case VompContent.ACT_START:
        _startArrived(sender, vomp);
        break;

      case VompContent.ACT_REJECT:
        _rejectArrived(sender, vomp);
        break;

      case VompContent.ACT_CANCEL:
        _cancelArrived(sender, vomp);
        break;

      case VompContent.ACT_BYE:
        _byeArrived(sender, vomp);
        break;

      case VompContent.ACT_BUSY:
        _busyArrived(sender, vomp);
        break;

      case VompContent.ACT_UPDATE:
        // engine-level: refresh port info (updatePipelines), no UI transition
        MagpieClient.instance.updatePipelines(sender.withoutTerminal(),
            _parseBridges(vomp.magpieBridges), _parseSockets(vomp.magpieSockets));
        break;

      default:
        assert(false, 'unknown vomp action: $act');
        break;
    }
  }

  /// 'dial': ring when idle, auto-reply 'busy' while calling/talking.
  Future<void> _dialArrived(ID sender, VompContent vomp) async {
    if (_meeting != null) {
      // auto-reply 'busy' while waiting (ringing) or talking
      ID? meeting = vomp.meeting;
      if (meeting != null) {
        VompContent content = VompContent.busy(meeting);
        await _sendSignaling(content);
        await _saveRecord('Busy.', to: sender.withoutTerminal());
      }
      return;
    }
    // late dial: the callee checks the envelope time, a signaling older
    // than the ringing timeout is dropped (only a chat record remains)
    DateTime sent = DateTime.now();
    num? time = vomp['time'];
    if (time != null) {
      sent = DateTime.fromMillisecondsSinceEpoch((time * 1000).toInt());
      if (DateTime.now().difference(sent) > _ringingTimeout) {
        logWarning('late dial ignored: $vomp');
        await _saveRecord('Missed call.');
        return;
      }
    }
    // register the caller's port info carried in the dial content, keep
    // the proposed media for the accept, then popup the incoming window
    MagpieClient.instance.updatePipelines(sender.withoutTerminal(),
        _parseBridges(vomp.magpieBridges), _parseSockets(vomp.magpieSockets));
    await invited(sender.withoutTerminal(),
      meeting: vomp.meeting, dialTime: sent, media: vomp.media);
  }

  /// 'accept': I am the caller, flip to connecting.
  Future<void> _acceptArrived(ID sender, VompContent vomp) async {
    ID? meeting = _meeting;
    if (_state != CallState.inviting || meeting == null) {
      assert(false, 'unexpected accept: state = $_state, sender = $sender');
      return;
    }
    _timer?.cancel();
    _talkSince = DateTime.now();
    // register the peer's port info carried in the accept content
    List<BridgeEntry> bridges = _parseBridges(vomp.magpieBridges);
    List<SocketEntry> sockets = _parseSockets(vomp.magpieSockets);
    MagpieClient.instance.updatePipelines(sender.withoutTerminal(), bridges, sockets);
    // generate the meeting key (32 bytes), then reply act='start'
    final random = Random();
    _meetingKey = Uint8List.fromList(
      List.generate(32, (_) => random.nextInt(256)));
    GlobalVariable shared = GlobalVariable();
    User? current = await shared.facebook.currentUser;
    if (current == null) {
      logError('failed to get current user');
      return;
    }
    // the start media is the accept-confirmed one (signaling.md section 3);
    // fall back to my own probe when the peer sent no media (old version)
    Map media = vomp.media ?? _proposedMedia ?? await _probeMedia();
    _confirmedMedia = media;
    // bare member IDs: no reliable local terminal name is available from
    // the framework yet, so the device terminal cannot be addressed
    Map participants = {
      '1': current.identifier.toString(),
      '2': sender.toString(),
    };
    _changeState(CallState.connecting);
    _startConnectingTimer();
    await _sendSignaling(VompContent.start(meeting,
      participants: participants,
      meetingKey: TransportableData.create(_meetingKey!),
      media: media));
    // both sides entered CONNECTING: bring up the audio pipeline
    _startEngine();
  }

  /// 'start': I am the callee, flip to connecting when still calling.
  void _startArrived(ID sender, VompContent vomp) {
    if (!sender.isSameAs(_peer)) {
      assert(false, 'unexpected start: state = $_state, sender = $sender');
      return;
    }
    if (_state == CallState.waiting || _state == CallState.connecting) {
      // CALLING -> CONNECTING on receiving 'start'; when the local user
      // accepted already, the state is CONNECTING here, but the meeting
      // key comes only with this command, so the pipeline still goes up
      if (_state == CallState.waiting) {
        _changeState(CallState.connecting);
        _startConnectingTimer();
      }
      // the meeting key comes with the 'start' command (protocol.md section 5)
      TransportableData? key = vomp.meetingKey;
      if (key != null) {
        Uint8List? bytes = key.bytes;
        if (bytes != null) {
          _meetingKey = bytes;
        }
      }
      // the confirmed media comes with the 'start' command too
      _confirmedMedia = vomp.media ?? _confirmedMedia;
      _startEngine();
      // probe the data plane right away: the internal tick (10 s) may
      // be too late for the CONNECTING deadline
      MagpieClient.instance.keepAlive();
    } else {
      assert(false, 'unexpected start: state = $_state, sender = $sender');
    }
  }

  /// 'reject': I am the caller, the peer declines the call.
  void _rejectArrived(ID sender, VompContent vomp) {
    if (_state != CallState.inviting || !sender.isSameAs(_peer)) {
      assert(false, 'unexpected reject: state = $_state, sender = $sender');
      return;
    }
    _endCall();
  }

  /// 'cancel': I am the callee, the caller gives up while ringing.
  void _cancelArrived(ID sender, VompContent vomp) {
    if (_state != CallState.waiting || !sender.isSameAs(_peer)) {
      assert(false, 'unexpected cancel: state = $_state, sender = $sender');
      return;
    }
    _endCall();
  }

  /// 'bye': the peer hung up.
  void _byeArrived(ID sender, VompContent vomp) {
    if (_state != CallState.connected || !sender.isSameAs(_peer)) {
      assert(false, 'unexpected bye: state = $_state, sender = $sender');
      return;
    }
    _endCall();
  }

  /// 'busy': I am the caller, the peer is ringing or talking elsewhere.
  void _busyArrived(ID sender, VompContent vomp) {
    if (_state != CallState.inviting || !sender.isSameAs(_peer)) {
      assert(false, 'unexpected busy: state = $_state, sender = $sender');
      return;
    }
    _endCall();
  }

  /// Send the signaling to the current peer.
  Future<void> _sendSignaling(VompContent? content) async {
    ID? peer = _peer;
    if (content == null || peer == null) {
      logError('failed to send signaling: $content, peer: $peer');
      return;
    }
    GlobalVariable shared = GlobalVariable();
    await shared.emitter.sendContent(content, receiver: peer);
  }

  /// Local audio capability: try to create the native Opus coder pair,
  /// fall back to PCM16 pass-through when the lib is unavailable
  /// (vomp/codec.md: Opus init failure => PCM16 pass-through).
  Future<Map> _probeMedia() async {
    // the FFI bindings must be initialized before any coder can be
    // created: without this the probe failed silently on every device,
    // so every call negotiated down to the PCM16 pass-through
    bool opus = await loadOpusLibrary();
    if (opus) {
      final gateway = createNativeOpusGateway(
        sampleRate: PayloadFormat.defaultSampleRate,
        channels: PayloadFormat.defaultChannels);
      opus = gateway != null;
      // the gateway is only for the capability check: release it at once
      gateway?.destroy();
    }
    return {
      'codec': opus ? 'opus' : 'pcm16',
      'rate': PayloadFormat.defaultSampleRate,
      'channels': PayloadFormat.defaultChannels,
    };
  }

  /// Intersect the dial's proposed media with the local capability:
  /// Opus only when both sides support it, otherwise the PCM16
  /// pass-through (signaling.md section 2).
  Map _negotiateMedia(Map proposed, Map local) {
    bool opus = proposed['codec'] == 'opus' && local['codec'] == 'opus';
    return {
      'codec': opus ? 'opus' : 'pcm16',
      'rate': PayloadFormat.defaultSampleRate,
      'channels': PayloadFormat.defaultChannels,
    };
  }

  /// Derive the direction keys from the meeting key (protocol.md
  /// section 5.1): K_1 = HKDF-SHA256(ikm=K, salt=utf8(meeting),
  /// info='vomp-1:sender=1'), K_2 likewise with 'vomp-1:sender=2'.
  Map<int, Uint8List> _deriveDirectionKeys(Uint8List key, ID meeting) {
    final salt = Uint8List.fromList(utf8.encode(meeting.toString()));
    Uint8List k1 = HkdfSha256.derive(key,
        salt: salt, info: Uint8List.fromList(utf8.encode('vomp-1:sender=1')));
    Uint8List k2 = HkdfSha256.derive(key,
        salt: salt, info: Uint8List.fromList(utf8.encode('vomp-1:sender=2')));
    return {1: k1, 2: k2};
  }

  /// New meeting ID: a temporary Polylogue ID derived from my
  /// meta.seed = 'call-xxxx' with a numbered suffix
  /// (vomp/protocol.md section 3.0).
  Future<ID?> _newMeetingID(User me) async {
    GlobalVariable shared = GlobalVariable();
    SignKey? sKey = await shared.database.getPrivateKeyForVisaSignature(me.identifier);
    if (sKey == null) {
      logError('failed to get private key of: ${me.identifier}');
      return null;
    }
    final suffix = _nextCallSuffix++;
    final seed = 'call-$suffix';
    Meta meta = Meta.generate(MetaType.MKM, sKey, seed: seed);
    return meta.generateID(NetworkID.POLYLOGUE);
  }

  /// Pack my bridges for the outbound signaling: deduped by bid+endpoint
  /// (signaling.md section 0: both sides must dedup).
  List<Map> _packBridges(List<BridgeEntry> bridges) {
    final seen = <String>{};
    final result = <Map>[];
    for (final entry in bridges) {
      final key = '${entry.host.address}:${entry.port}:${entry.bid}';
      if (!seen.add(key)) {
        continue; // duplicated entry
      }
      result.add({'host': entry.host.address, 'port': entry.port, 'bid': entry.bid});
    }
    return result;
  }

  /// Pack my sockets for the outbound signaling: deduped by endpoint.
  List<Map> _packSockets(List<SocketEntry> sockets) {
    final seen = <String>{};
    final result = <Map>[];
    for (final entry in sockets) {
      final key = '${entry.host.address}:${entry.port}';
      if (!seen.add(key)) {
        continue; // duplicated entry
      }
      result.add({'host': entry.host.address, 'port': entry.port});
    }
    return result;
  }

  /// Parse the raw 'magpie-bridges' list from inbound signaling
  /// (the lists come from untrusted signaling, malformed entries dropped)
  /// and dedup by bid+endpoint.
  List<BridgeEntry> _parseBridges(List? raw) {
    final seen = <String>{};
    final result = <BridgeEntry>[];
    for (final obj in raw ?? const []) {
      final entry = BridgeEntry.parse(obj);
      if (entry == null) {
        continue; // malformed entry
      }
      final key = '${entry.host.address}:${entry.port}:${entry.bid}';
      if (!seen.add(key)) {
        continue; // duplicated entry
      }
      result.add(entry);
    }
    return result;
  }

  /// Parse the raw 'magpie-sockets' list from inbound signaling
  /// and dedup by endpoint.
  List<SocketEntry> _parseSockets(List? raw) {
    final seen = <String>{};
    final result = <SocketEntry>[];
    for (final obj in raw ?? const []) {
      final entry = SocketEntry.parse(obj);
      if (entry == null) {
        continue; // malformed entry
      }
      final key = '${entry.host.address}:${entry.port}';
      if (!seen.add(key)) {
        continue; // duplicated entry
      }
      result.add(entry);
    }
    return result;
  }

  /// Flip to a new state with a trace.
  void _changeState(CallState next) {
    logDebug('call state: $_state -> $next');
    _state = next;
    notifyListeners();
  }

  /// State 6: stay 1 second, then close the window automatically.
  void _endCall() {
    _timer?.cancel();
    _connectingTimer?.cancel();
    _connectingTimer = null;
    // tear the audio pipeline down on every ending path
    unawaited(_stopEngine());
    _changeState(CallState.ended);
    Timer(const Duration(seconds: 1), _dismiss);
  }

  /// Auto cancel after ringing too long without accept/reject/busy:
  /// the deadline is the dial time plus the ringing timeout.
  void _startTimeoutTimer(DateTime dialTime) {
    _timer?.cancel();
    Duration remaining = dialTime.add(_ringingTimeout).difference(DateTime.now());
    if (remaining < Duration.zero) {
      remaining = Duration.zero;
    }
    _timer = Timer(remaining, _timeoutArrived);
  }
  Timer? _timer;

  /// Arm the connecting deadline once: 10 s from the first entry into
  /// CONNECTING; a later 'start' command must not extend it.
  void _startConnectingTimer() {
    _connectingTimer ??= Timer(_connectingTimeout, _connectingTimeoutArrived);
  }
  Timer? _connectingTimer;

  /// Deadline reached while still CONNECTING: no packet ever arrived from
  /// the peer - synthesize a local record and quit (protocol.md section
  /// 3.4; both sides record the same text, section 3.5).
  void _connectingTimeoutArrived() {
    if (_state != CallState.connecting) {
      return;
    }
    _saveRecord('Connection failed.');
    _endCall();
  }

  /// Timeout arrived: both the caller and the callee quit the ringing
  /// call and leave a local timeout record - 'No answer.' for the caller,
  /// 'Missed call.' for the callee.
  void _timeoutArrived() {
    switch (_state) {
      case CallState.inviting:
        _saveRecord('No answer.');
        _endCall();
        break;
      case CallState.waiting:
        _saveRecord('Missed call.');
        _endCall();
        break;
      default:
        break;
    }
  }

  /// Synthesize a local record into the chat history (sent side, no
  /// attribution): the outbound signaling echoes and the timeout records.
  /// [to] overrides the chat box when the record belongs to another peer
  /// (e.g. the 'busy' auto-reply to a third-party dial).
  Future<void> _saveRecord(String text, {ID? to}) async {
    ID? peer = to ?? _peer;
    if (peer == null) {
      logError('failed to get peer');
      return;
    }
    GlobalVariable shared = GlobalVariable();
    User? me = await shared.facebook.currentUser;
    if (me == null) {
      logError('failed to get current user');
      return;
    }
    final head = Envelope.create(sender: me.identifier, receiver: peer);
    final body = CallRecordContent.fromText(text: text);
    final iMsg = InstantMessage.create(head, body);
    Amanuensis clerk = Amanuensis();
    await clerk.saveInstantMessage(iMsg);
  }

  /// Bring up the audio pipeline when both sides entered CONNECTING.
  Future<void> _startEngine() async {
    Uint8List? key = _meetingKey;
    ID? peer = _peer;
    ID? meeting = _meeting;
    if (key == null || peer == null || meeting == null) {
      logError('failed to start engine: $key, $peer');
      return;
    }
    CallEngine? engine = _engine;
    if (engine != null) {
      await engine.stop();
    }
    engine = CallEngine(peer: peer, localId: _localId, meetingKey: key,
      keys: _deriveDirectionKeys(key, meeting), media: _confirmedMedia);
    _engine = engine;
    engine.onDataPlaneReady = connected;
    engine.onPortInfoUpdated = () {
      // push my fresh port info to the peer (signaling.md section 8)
      List<BridgeEntry> bridges = MagpieClient.instance.myBridges;
      List<SocketEntry> sockets = MagpieClient.instance.mySockets;
      _sendSignaling(VompContent.update(meeting,
        bridges: _packBridges(bridges),
        sockets: _packSockets(sockets)));
    };
    await engine.start();
  }

  /// Tear the audio pipeline down on hang-up: stop the engine and drop
  /// the transport pipelines to the peer.
  Future<void> _stopEngine() async {
    CallEngine? engine = _engine;
    _engine = null;
    ID? peer = _peer;
    await engine?.stop();
    if (peer != null) {
      MagpieClient.instance.removePipelines(peer.withoutTerminal());
    }
  }

  Future<void> _popup() async {
    await Get.generalDialog(
      barrierDismissible: false,
      barrierColor: const Color(0xFF1C1C1E),
      transitionDuration: const Duration(milliseconds: 200),
      pageBuilder: (context, animation, secondaryAnimation) => const CallPage(),
      transitionBuilder: (context, animation, secondaryAnimation, child) =>
          FadeTransition(opacity: animation, child: child),
    );
  }

  Future<void> _dismiss() async {
    if (_state != CallState.ended) {
      return;
    }
    Get.back();
    _peer = null;
    _meeting = null;
    _meetingKey = null;
    _localId = 0;
    _talkSince = null;
    _proposedMedia = null;
    _confirmedMedia = null;
    _changeState(CallState.idle);
  }

